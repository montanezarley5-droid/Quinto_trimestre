public class Grupos {

    public int getIdGrupos() {
        return idGrupos;
    }

    public void setIdGrupos(int idGrupos) {
        this.idGrupos = idGrupos;
    }

    public String getNombreGrupo() {
        return nombreGrupo;
    }

    public void setNombreGrupo(String nombreGrupo) {
        this.nombreGrupo = nombreGrupo;
    }

    public int getCantidad() {
        return cantidad;
    }

    public void setCantidad(int cantidad) {
        this.cantidad = cantidad;
    }

    public int getIdUsuarioDocente() {
        return idUsuarioDocente;
    }

    public void setIdUsuarioDocente(int idUsuarioDocente) {
        this.idUsuarioDocente = idUsuarioDocente;
    }

    public int getIdAulas() {
        return idAulas;
    }

    public void setIdAulas(int idAulas) {
        this.idAulas = idAulas;
    }
    private int idGrupos;
    private String nombreGrupo;
    private int cantidad;
    private int idUsuarioDocente;
    private int idAulas;
}
